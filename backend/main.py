from fastapi import FastAPI
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from pydantic import BaseModel

app=FastAPI(title="Citizen Rights Assistant")

# CORS: allow the Vite dev server (add the deployed frontend URL later)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173","http://127.0.0.1:5173"],
    allow_methods=["*"],
    allow_headers=["*"],
)


class ChatRequest(BaseModel):
    question: str


# Contract: errors return {"error": "message"} with a proper HTTP status.
# FastAPI's default validation error uses {"detail": ...}, so override it.
@app.exception_handler(RequestValidationError)
async def validation_exception_handler(request, exc):
    return JSONResponse(
        status_code=422,
        content={"error": 'Request body must be {"question": "string"}'},
    )


@app.get("/health")
async def health():
    return {"status": "ok"}


